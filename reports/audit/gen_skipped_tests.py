#!/usr/bin/env python3
"""Generate reports/audit/skipped_tests.md from an ACTUAL pytest run (T6). Nothing is typed by hand.

Usage (from a clean `git archive <sha>` export):
  python -m pytest -q -rs -p no:cacheprovider --junitxml=J.xml > RS.log
  python reports/audit/gen_skipped_tests.py <export_root> J.xml RS.log <sha> <out.md>

Node ID, skip message and test-case pass/fail come from the junit XML; file:line and the exact reason
string come from the `-rs` summary lines (SKIPPED [n] file:line: reason). The category is assigned by
the regex rules in CATEGORIES below (T6 judgement, stated in the output). "Hides a required check?"
is computed: for sim spec-case skips, the same spec key must be checked by the analytic reference
test docs/math/sensor-spec/test_reference.py::test_case[TCxx], which must have PASSED in the same run.
"""
import json, re, sys, os, collections
import xml.etree.ElementTree as ET

root, jx, rslog, sha, out = sys.argv[1:6]

CATEGORIES = [  # (regex on reason, category, requirement mapping)
    (r"dead.reckoning|WGS84|geodesy|great circle|rhumb|grid convergence|navigation|wind/track|position",
     "Out of scope: navigation / position / distance (heading-only rule)", "none (excluded by the heading-only scope; must not be implemented)"),
    (r"circular statistics|first-order|analytic formula|analytic ratio",
     "Analysis formula, not a simulator quantity", "none for the sim; formula checked analytically in sensor-spec"),
    (r"dipole|straight-wire",
     "Interference source model not in sim (motor field is k*I, [ASSUMED])", "none; documented limitation"),
    (r"WMM",
     "Declination error model not in sim (uniform field)", "R4 uses a user constant; no WMM (documented limitation)"),
    (r"0\.15 uT LSB|generic consumer part",
     "Non-RM3100 parameter (generic 0.15 uT LSB part)", "none"),
]

def cat(reason):
    for rx, c, req in CATEGORIES:
        if re.search(rx, reason, re.I): return c, req
    return "UNCATEGORISED (review by hand)", "UNKNOWN"

t = ET.parse(jx)
cases = list(t.iter("testcase"))
skipped = [c for c in cases if c.find("skipped") is not None]
status = {}
for c in cases:
    nid = c.attrib["classname"].replace(".", "/") + ".py::" + c.attrib["name"]
    st = "skipped" if c.find("skipped") is not None else ("failed" if (c.find("failure") is not None or c.find("error") is not None) else "passed")
    status[nid] = st
# -rs lines: reason -> file:line (reasons are unique per case here; counted to be sure)
rs = collections.defaultdict(list)
for l in open(rslog):
    m = re.match(r"SKIPPED \[(\d+)\] ([^:]+):(\d+): (.*)$", l.rstrip("\n"))
    if m: rs[m.group(4)].append((m.group(2), int(m.group(3)), int(m.group(1))))
_tcp = os.path.join(root, "docs/math/sensor-spec/test_cases.json")
tc = {c["id"]: c for c in json.load(open(_tcp))["cases"]} if os.path.exists(_tcp) else {}

summ = re.search(r"(\d+) passed.*?(\d+) skipped", open(rslog).read())
rows = []
for c in skipped:
    nid = c.attrib["classname"].replace(".", "/") + ".py::" + c.attrib["name"]
    msg = c.find("skipped").attrib.get("message", "")
    loc = rs.get(msg, [("?", 0, 0)])[0]
    m = re.match(r"(TC\d\d)\.([^:]+): (.*)", msg)
    category, req = cat(m.group(3) if m else msg)
    hides = "UNKNOWN"
    if m:
        cid, key = m.group(1), re.sub(r"\[\d+\]$", "", m.group(2))
        ref = f"docs/math/sensor-spec/test_reference.py::test_case[{cid}]"
        ref_ok = status.get(ref) == "passed"
        key_in_spec = cid in tc and key in tc[cid].get("expected", {})
        if ref_ok and key_in_spec:
            hides = f"No. Key checked analytically by `{ref}` (PASSED this run); only the sim cross-check is N/A"
        else:
            hides = f"CHECK: reference test status={status.get(ref)!r}, key in spec={key_in_spec}"
    rows.append((nid, f"{loc[0]}:{loc[1]}", msg, category, req, hides))

n_un = sum(r[3].startswith("UNCATEGORISED") for r in rows)
n_h = sum(not r[5].startswith("No.") for r in rows)
L = [f"# Skipped tests at `{sha}` (generated, T6)", "",
     f"Generated by `reports/audit/gen_skipped_tests.py` from an actual run on a clean `git archive {sha}` export:",
     "`python -m pytest -q -rs -p no:cacheprovider --junitxml=...` (repo root, venv from requirements.txt + pyserial).",
     f"Run result: **{summ.group(1)} passed, {summ.group(2)} skipped**, 0 failed. Skipped test cases in the junit XML: **{len(skipped)}**.",
     "Raw evidence: `reports/audit/raw/pytest_rs_" + sha + ".log`, `reports/audit/raw/junit_" + sha + ".xml`.", "",
     "Column notes: *Skip location* is the `file:line` pytest reports for the skip call (`-rs`). *Reason* is the exact skip string.",
     "*Category* comes from the regex rules in the generator (T6 judgement). *Hides a required check?* is computed: the same spec key",
     "must be asserted by the analytic reference test for that case, and that test must have PASSED in the same run.", "",
     "## Summary", "", "| Category | Count | Requirement mapping |", "|---|---|---|"]
cc = collections.Counter((r[3], r[4]) for r in rows)
for (c, req), n in sorted(cc.items(), key=lambda x: -x[1]): L.append(f"| {c} | {n} | {req} |")
L += ["", f"Uncategorised: {n_un}. Skips that may hide a required check: **{n_h}**.", "",
      "## All skipped tests", "", "| # | Node ID | Skip location | Exact reason | Category | Hides a required check? |", "|---|---|---|---|---|---|"]
for i, r in enumerate(rows, 1):
    L.append(f"| {i} | `{r[0]}` | `{r[1]}` | {r[2]} | {r[3]} | {r[5]} |")
open(out, "w").write("\n".join(L) + "\n")
print(f"{len(rows)} skipped; uncategorised={n_un}; possibly hiding={n_h}")
